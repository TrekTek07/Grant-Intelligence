// Website -> run-module01 launcher
//         -> immediate Processing status
//         -> polls Supabase module_results
//         -> displays report when completed

const $ = (id) => document.getElementById(id);

let session = null;
let profile = null;
let project = null;

let pollTimer = null;
let processingStartedAt = null;


